<#
.SYNOPSIS
    Generates the Android string resources from the iOS app's Localizable.xcstrings.

.DESCRIPTION
    Writes app/src/main/res/values{,-hr,-uk}/strings.xml so both apps show the same text.
    Android-only strings live in strings_android.xml and are not touched.

    Key names: format specifiers and spaces are dropped ("transactions_for %@" -> transactions_for,
    "top categories" -> top_categories). Default category and source names get a seed_ prefix
    ("Bank Card" -> seed_bank_card). Specifiers become positional Android ones (%@ -> %1$s,
    %lld -> %1$d), and plural variations become <plurals>.

.EXAMPLE
    pwsh tools/sync-ios-strings.ps1 -XcStrings "D:\github projects\ledgerIos\ledger\Localizable.xcstrings"
#>
param(
    [Parameter(Mandatory)] [string] $XcStrings,
    [string] $ResDir = (Join-Path $PSScriptRoot '..\app\src\main\res')
)

$ErrorActionPreference = 'Stop'

$catalog = Get-Content $XcStrings -Raw -Encoding UTF8 | ConvertFrom-Json -AsHashtable
$languages = [ordered]@{ en = 'values'; hr = 'values-hr'; uk = 'values-uk' }

# Ordinal comparer: the catalog has both "Savings" (default source) and "savings" (screen title).
$seedNames = [System.Collections.Generic.Dictionary[string, string]]::new([StringComparer]::Ordinal)
foreach ($key in 'Groceries', 'Restaurants', 'Transport', 'Housing', 'Utilities', 'Health', 'Entertainment',
    'Shopping', 'Subscriptions', 'Other', 'Salary', 'Freelance', 'Gifts', 'Investments', 'Cash', 'Bank Card', 'Savings') {
    $seedNames[$key] = 'seed_' + ($key.ToLowerInvariant() -replace ' ', '_')
}
$skippedKeys = @('%@')

function Get-ResourceName([string] $key) {
    if ($seedNames.ContainsKey($key)) { return $seedNames[$key] }
    $name = ($key -replace '%(\d+\$)?(lld|ld|d|@)', '').Trim().ToLowerInvariant()
    $name = ($name -replace '[^a-z0-9]+', '_').Trim('_')
    if ($name -notmatch '^[a-z]') { $name = "s_$name" }
    return $name
}

function Convert-Value([string] $value) {
    $counter = @{ n = 0 }
    $value = [regex]::Replace($value, '%(?:(\d+)\$)?(lld|ld|d|@)', [System.Text.RegularExpressions.MatchEvaluator] {
            param($m)
            $counter.n++
            $position = if ($m.Groups[1].Success) { $m.Groups[1].Value } else { $counter.n }
            $type = if ($m.Groups[2].Value -eq '@') { 's' } else { 'd' }
            "%$position`$$type"
        })
    if ($value -match '%(?!\d+\$[sd])') { Write-Warning "Unescaped % in: $value" }
    $value = $value.Replace('&', '&amp;').Replace('<', '&lt;').Replace('>', '&gt;')
    $value = $value.Replace('\', '\\').Replace("'", "\'").Replace('"', '\"')
    $value = $value -replace "`r?`n", '\n'
    if ($value -match '^[@?]') { $value = '\' + $value }
    return $value
}

$names = @{}
foreach ($key in $catalog.strings.Keys) {
    if ($key -in $skippedKeys) { continue }
    $name = Get-ResourceName $key
    if ($names.ContainsKey($name)) { throw "Keys '$key' and '$($names[$name])' both map to '$name'" }
    $names[$name] = $key
}

foreach ($language in $languages.Keys) {
    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add('<?xml version="1.0" encoding="utf-8"?>')
    $lines.Add('<!-- Generated by tools/sync-ios-strings.ps1 from the iOS Localizable.xcstrings. Do not edit by hand. -->')
    $lines.Add('<resources>')
    if ($language -eq 'en') {
        $lines.Add('    <string name="app_name" translatable="false">Ledger</string>')
    }
    foreach ($name in ($names.Keys | Sort-Object)) {
        $entry = $catalog.strings[$names[$name]]
        $localization = $entry.localizations ? $entry.localizations[$language] : $null
        if (-not $localization) { continue }
        if ($localization.stringUnit) {
            $lines.Add("    <string name=""$name"">$(Convert-Value $localization.stringUnit.value)</string>")
        }
        elseif ($localization.variations -and $localization.variations.plural) {
            $lines.Add("    <plurals name=""$name"">")
            foreach ($quantity in 'zero', 'one', 'two', 'few', 'many', 'other') {
                $form = $localization.variations.plural[$quantity]
                if ($form) { $lines.Add("        <item quantity=""$quantity"">$(Convert-Value $form.stringUnit.value)</item>") }
            }
            $lines.Add('    </plurals>')
        }
    }
    $lines.Add('</resources>')

    $dir = Join-Path $ResDir $languages[$language]
    New-Item -ItemType Directory -Force $dir | Out-Null
    $path = Join-Path $dir 'strings.xml'
    [System.IO.File]::WriteAllText($path, ($lines -join "`n") + "`n", [System.Text.UTF8Encoding]::new($false))
    Write-Host "Wrote $path"
}
